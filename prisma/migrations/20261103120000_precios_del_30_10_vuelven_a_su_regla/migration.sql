     AND pl."margen" IS NOT DISTINCT FROM r.margen_antes
     AND pl."reglaPrecio"::text IS NOT DISTINCT FROM r.regla_antes
     AND pl."recargoFijoUnidad" IS NOT DISTINCT FROM r.recargo_antes
  RETURNING pl."id"
)
